-- Restrict staff RPCs to the server-side Edge Function gateway.
create table if not exists public.barber_admin_login_attempts(
 id bigint generated by default as identity primary key,
 ip_hash text not null,
 attempted_at timestamptz not null default now()
);
create index if not exists barber_admin_login_attempts_ip_time_idx
 on public.barber_admin_login_attempts(ip_hash,attempted_at desc);
alter table public.barber_admin_login_attempts enable row level security;
revoke all on public.barber_admin_login_attempts from public,anon,authenticated;
grant select,insert,delete on public.barber_admin_login_attempts to service_role;
drop policy if exists barber_admin_login_attempts_deny_clients on public.barber_admin_login_attempts;
create policy barber_admin_login_attempts_deny_clients on public.barber_admin_login_attempts
 for all to anon,authenticated using(false) with check(false);

create or replace function public.barber_admin_allow_login(p_ip_hash text)
returns boolean language plpgsql security definer
set search_path=pg_catalog,public,pg_temp as $$
declare v_count integer;
begin
 if p_ip_hash is null or length(p_ip_hash)<>64 or p_ip_hash !~ '^[0-9a-f]{64}$' then
  raise exception 'Identificador de origen no válido' using errcode='22023';
 end if;
 perform pg_advisory_xact_lock(hashtextextended(p_ip_hash,1));
 delete from public.barber_admin_login_attempts where attempted_at<now()-interval '24 hours';
 select count(*) into v_count from public.barber_admin_login_attempts
  where ip_hash=p_ip_hash and attempted_at>now()-interval '1 hour';
 if v_count>=10 then return false; end if;
 insert into public.barber_admin_login_attempts(ip_hash) values(p_ip_hash);
 return true;
end $$;
revoke all on function public.barber_admin_allow_login(text) from public,anon,authenticated;
grant execute on function public.barber_admin_allow_login(text) to service_role;

do $staff$
declare f record;
begin
 for f in select p.oid::regprocedure as signature
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.prosecdef
   and (
    p.proname like 'barber_admin_%' or p.proname like 'barber_loyalty_%'
    or p.proname like 'barber_promotion_admin_%' or p.proname like 'barber_promotions_admin_%'
    or p.proname like 'barber_promotion_suggestion_settings_admin_%'
    or p.proname in ('barber_promotions_generate_daily_suggestions','barber_services_admin_list','barber_service_admin_save')
   )
   and p.proname not in ('barber_loyalty_register_customer','barber_loyalty_allow_registration','barber_admin_allow_login')
 loop
  execute format('revoke all on function %s from public,anon,authenticated',f.signature);
  execute format('grant execute on function %s to service_role',f.signature);
 end loop;
end
$staff$;
grant select on public.barber_admin_sessions to service_role;
