create sequence if not exists public.barber_sales_folio_seq;
create table public.reservas (
 id uuid primary key default gen_random_uuid(), nombre text not null, telefono text, wa text,
 serv text, servicio text, precio integer, barbero text default 'EdgarMay',
 fecha date not null, hora text not null, estado text default 'pendiente',
 stock_key text, creado timestamptz default now()
);
create index reservas_fecha_hora_idx on public.reservas(fecha,hora,barbero);
create table public.barber_admin_config (
 id boolean primary key default true check(id), username text not null default 'EdgarMay',
 pin_hash text, updated_at timestamptz not null default now()
);
insert into public.barber_admin_config(id,username,pin_hash) values(true,'EdgarMay',null);
create table public.barber_admin_sessions (
 token uuid primary key default gen_random_uuid(), username text not null default 'EdgarMay',
 created_at timestamptz not null default now(), expires_at timestamptz not null default now()+interval '12 hours',
 revoked_at timestamptz
);
create index barber_admin_sessions_expiry_idx on public.barber_admin_sessions(expires_at) where revoked_at is null;
create table public.barber_sales (
 id bigint generated by default as identity primary key,
 folio text not null unique default ('EB-'||to_char(now(),'YYMMDD')||'-'||lpad(nextval('public.barber_sales_folio_seq')::text,5,'0')),
 reserva_id uuid unique references public.reservas(id) on delete restrict,
 cliente text not null, servicio text not null, barbero text not null,
 total numeric(12,2) not null check(total>=0),
 metodo text not null check(metodo in ('Efectivo','Transferencia','Tarjeta','Mixto')),
 recibido numeric(12,2) not null default 0 check(recibido>=0),
 cambio numeric(12,2) not null default 0 check(cambio>=0), creado timestamptz not null default now()
);
alter table public.reservas enable row level security;
alter table public.barber_admin_config enable row level security;
alter table public.barber_admin_sessions enable row level security;
alter table public.barber_sales enable row level security;
revoke all on public.reservas,public.barber_admin_config,public.barber_admin_sessions,public.barber_sales from anon,authenticated;

create or replace function public.barber_admin_login(p_username text,p_password text)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,extensions,pg_temp as $$
declare v_token uuid; v_hash text;
begin
 select pin_hash into v_hash from public.barber_admin_config where id=true and lower(username)=lower(trim(coalesce(p_username,'')));
 if v_hash is null or p_password is null or extensions.crypt(p_password,v_hash)<>v_hash then
  raise exception 'Usuario o contraseña incorrectos' using errcode='28000';
 end if;
 insert into public.barber_admin_sessions(username,expires_at) values(trim(p_username),now()+interval '12 hours') returning token into v_token;
 return jsonb_build_object('token',v_token,'expires_at',now()+interval '12 hours','username',trim(p_username));
end $$;

create or replace function public.barber_admin_reservations(p_token uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
begin
 if not exists(select 1 from public.barber_admin_sessions s where s.token=p_token and s.revoked_at is null and s.expires_at>now()) then raise exception 'Sesión inválida o vencida' using errcode='28000'; end if;
 return coalesce((select jsonb_agg(to_jsonb(r) order by r.fecha,r.hora) from public.reservas r where r.fecha>=current_date),'[]'::jsonb);
end $$;
create or replace function public.barber_admin_sales(p_token uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
begin
 if not exists(select 1 from public.barber_admin_sessions s where s.token=p_token and s.revoked_at is null and s.expires_at>now()) then raise exception 'Sesión inválida o vencida' using errcode='28000'; end if;
 return coalesce((select jsonb_agg(to_jsonb(s) order by s.creado desc) from public.barber_sales s where s.creado::date=current_date),'[]'::jsonb);
end $$;
create or replace function public.barber_admin_set_status(p_token uuid,p_id uuid,p_estado text)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare v_estado text;
begin
 if not exists(select 1 from public.barber_admin_sessions s where s.token=p_token and s.revoked_at is null and s.expires_at>now()) then raise exception 'Sesión inválida o vencida' using errcode='28000'; end if;
 if p_estado not in ('pendiente','confirmada','en_servicio','atendida','rechazada','cancelada') then raise exception 'Estado no permitido'; end if;
 update public.reservas set estado=p_estado where id=p_id returning estado into v_estado;
 if not found then raise exception 'Reserva no encontrada'; end if;
 return jsonb_build_object('id',p_id,'estado',v_estado);
end $$;
create or replace function public.barber_admin_create_sale(p_token uuid,p_reserva_id uuid,p_metodo text,p_recibido numeric)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare r public.reservas; s public.barber_sales; v_received numeric(12,2);
begin
 if not exists(select 1 from public.barber_admin_sessions x where x.token=p_token and x.revoked_at is null and x.expires_at>now()) then raise exception 'Sesión inválida o vencida'; end if;
 if p_metodo not in ('Efectivo','Transferencia','Tarjeta','Mixto') then raise exception 'Método de pago no válido'; end if;
 select * into r from public.reservas where id=p_reserva_id for update;
 if not found then raise exception 'Reserva no encontrada'; end if;
 if exists(select 1 from public.barber_sales where reserva_id=p_reserva_id) then raise exception 'Esta reserva ya tiene un cobro registrado'; end if;
 v_received:=greatest(coalesce(p_recibido,r.precio,0),0);
 if p_metodo='Efectivo' and v_received<coalesce(r.precio,0) then raise exception 'El efectivo recibido es insuficiente'; end if;
 insert into public.barber_sales(reserva_id,cliente,servicio,barbero,total,metodo,recibido,cambio)
 values(r.id,coalesce(r.nombre,'Cliente'),coalesce(r.servicio,r.serv,'Servicio'),coalesce(r.barbero,'EdgarMay'),coalesce(r.precio,0),p_metodo,v_received,case when p_metodo='Efectivo' then greatest(v_received-coalesce(r.precio,0),0) else 0 end)
 returning * into s;
 update public.reservas set estado='atendida' where id=r.id;
 return jsonb_build_object('id',s.id,'folio',s.folio,'reserva_id',s.reserva_id,'cliente',s.cliente,'servicio',s.servicio,'barbero',s.barbero,'total',s.total,'metodo',s.metodo,'recibido',s.recibido,'cambio',s.cambio);
end $$;
create or replace function public.barber_admin_create_walkin_sale(p_token uuid,p_cliente text,p_servicio_id integer,p_barbero_id integer,p_metodo text,p_recibido numeric)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare v_service record; v_barber text; v_received numeric(12,2); v_sale public.barber_sales;
begin
 if not exists(select 1 from public.barber_admin_sessions where token=p_token and revoked_at is null and expires_at>now()) then raise exception 'Sesión administrativa inválida o vencida'; end if;
 if p_metodo not in ('Efectivo','Transferencia','Tarjeta','Mixto') or p_servicio_id not between 1 and 9 or p_barbero_id not in (1,2) then raise exception 'Datos de venta inválidos'; end if;
 select * into v_service from (values (1,'Corte Clásico',160),(2,'Corte Desvanecido',180),(3,'Corte Infantil',130),(4,'Alineación de Ceja',40),(5,'Alineación de Barba',80),(6,'Corte + Masaje',280),(7,'Corte y Lavado de Cabello',250),(8,'VIP',400),(9,'Premium',550)) as s(id,name,price) where s.id=p_servicio_id;
 v_barber:=case when p_barbero_id=1 then 'EdgarMay' else 'Staff 2' end;
 v_received:=greatest(coalesce(p_recibido,v_service.price),0);
 if p_metodo='Efectivo' and v_received<v_service.price then raise exception 'El efectivo recibido es insuficiente'; end if;
 insert into public.barber_sales(cliente,servicio,barbero,total,metodo,recibido,cambio)
 values(coalesce(nullif(trim(p_cliente),''),'Cliente mostrador'),v_service.name,v_barber,v_service.price,p_metodo,v_received,case when p_metodo='Efectivo' then greatest(v_received-v_service.price,0) else 0 end)
 returning * into v_sale;
 return jsonb_build_object('id',v_sale.id,'folio',v_sale.folio,'total',v_sale.total,'cliente',v_sale.cliente,'servicio',v_sale.servicio,'barbero',v_sale.barbero,'metodo',v_sale.metodo,'recibido',v_sale.recibido,'cambio',v_sale.cambio,'creado',v_sale.creado);
end $$;
create or replace function public.barber_create_reservation(p_barbero_id integer,p_fecha date,p_hora text,p_nombre text,p_notas text,p_servicio_id integer,p_telefono text)
returns uuid language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare v_id uuid; v_barbero text; v_servicio text; v_precio integer;
begin
 if p_barbero_id=1 then v_barbero:='EdgarMay'; elsif p_barbero_id=2 then v_barbero:='Staff 2'; else raise exception 'Barbero no válido'; end if;
 select s.nombre,s.precio into v_servicio,v_precio from (values (1,'Corte Clásico',160),(2,'Corte Desvanecido',180),(3,'Corte Infantil',130),(4,'Alineación de Ceja',40),(5,'Alineación de Barba',80),(6,'Corte + Masaje',280),(7,'Corte y Lavado de Cabello',250),(8,'VIP',400),(9,'Premium',550)) as s(id,nombre,precio) where s.id=p_servicio_id;
 if v_servicio is null then raise exception 'Servicio no válido'; end if;
 if p_fecha<current_date then raise exception 'La fecha ya pasó'; end if;
 if extract(isodow from p_fecha)=7 then raise exception 'Domingo cerrado'; end if;
 if exists(select 1 from public.reservas r where r.fecha=p_fecha and r.hora=left(p_hora,5) and r.barbero=v_barbero and lower(coalesce(r.estado,'pendiente')) not in ('rechazada','cancelada','atendida')) then raise exception 'Ese horario ya fue reservado'; end if;
 insert into public.reservas(nombre,telefono,wa,serv,servicio,precio,barbero,fecha,hora,estado,stock_key)
 values(trim(p_nombre),trim(p_telefono),trim(p_telefono),v_servicio,v_servicio,v_precio,v_barbero,p_fecha,left(trim(p_hora),5),'pendiente',p_fecha::text||'_'||v_barbero||'_'||left(trim(p_hora),5)) returning id into v_id;
 return v_id;
end $$;
create or replace function public.barber_public_schedule(p_fecha date,p_barbero_id integer)
returns table(hora text,disponible boolean) language sql stable security definer set search_path=pg_catalog,public,pg_temp as $$
 select to_char(t,'HH24:MI'),
 not exists(select 1 from public.reservas r where r.fecha=p_fecha and r.hora=to_char(t,'HH24:MI')
 and r.barbero=case when p_barbero_id=1 then 'EdgarMay' else 'Staff 2' end
 and lower(coalesce(r.estado,'pendiente')) not in ('rechazada','cancelada','atendida'))
 from generate_series(p_fecha+time '13:30',p_fecha+time '20:30',interval '30 minutes') t
 where extract(isodow from p_fecha)<>7 order by t;
$$;
