create table if not exists public.barber_promotions (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null default '',
  status text not null default 'draft'
    check (status in ('draft','pending_review','approved','rejected','paused','expired')),
  discount_type text not null check (discount_type in ('percent','fixed_price')),
  discount_value numeric(10,2) not null check (discount_value > 0),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  weekdays smallint[] not null default array[0,1,2,3,4,5,6]::smallint[],
  start_time time,
  end_time time,
  source text not null default 'manual' check (source in ('manual','daily_suggestion')),
  max_uses integer check (max_uses is null or max_uses > 0),
  uses_count integer not null default 0 check (uses_count >= 0),
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at),
  check (start_time is null or end_time is null or end_time > start_time),
  check (discount_type <> 'percent' or discount_value <= 100)
);

create table if not exists public.barber_promotion_services (
  promotion_id uuid not null references public.barber_promotions(id) on delete cascade,
  service_id integer not null references public.barber_services(id) on delete restrict,
  primary key (promotion_id, service_id)
);

create index if not exists barber_services_active_order_idx
  on public.barber_services (is_active, display_order);
create index if not exists barber_promotions_public_window_idx
  on public.barber_promotions (status, starts_at, ends_at);

alter table public.barber_services enable row level security;
alter table public.barber_promotions enable row level security;
alter table public.barber_promotion_services enable row level security;

-- No anonymous direct writes. Public reads are exposed through narrow RPCs below.
drop policy if exists barber_services_public_read on public.barber_services;
create policy barber_services_public_read on public.barber_services
  for select to anon, authenticated using (is_active);

drop policy if exists barber_promotions_public_read on public.barber_promotions;
create policy barber_promotions_public_read on public.barber_promotions
  for select to anon, authenticated using (status = 'approved');

drop policy if exists barber_promotion_services_public_read on public.barber_promotion_services;
create policy barber_promotion_services_public_read on public.barber_promotion_services
  for select to anon, authenticated using (
    exists (
      select 1 from public.barber_promotions p
      where p.id = promotion_id and p.status = 'approved'
    )
  );

create or replace function public.barber_services_public()
returns table (
  id integer, name text, description text, duration_minutes integer, price numeric, display_order integer
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select s.id, s.name, s.description, s.duration_minutes, s.price, s.display_order
  from public.barber_services s
  where s.is_active
  order by s.display_order, s.name;
$$;

create or replace function public.barber_promotions_public()
returns table (
  id uuid, title text, description text, discount_type text, discount_value numeric,
  starts_at timestamptz, ends_at timestamptz, weekdays smallint[],
  start_time time, end_time time, service_ids integer[]
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select p.id, p.title, p.description, p.discount_type, p.discount_value,
         p.starts_at, p.ends_at, p.weekdays, p.start_time, p.end_time,
         coalesce(array_agg(ps.service_id) filter (where ps.service_id is not null), '{}'::integer[])
  from public.barber_promotions p
  left join public.barber_promotion_services ps on ps.promotion_id = p.id
  where p.status = 'approved'
    and p.ends_at > now()
    and (p.max_uses is null or p.uses_count < p.max_uses)
  group by p.id
  order by p.starts_at;
$$;

-- Admin mutations require a live token from the existing admin-session table.
create or replace function public.barber_services_admin_list(p_token uuid)
returns setof public.barber_services
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1 from public.barber_admin_sessions s
    where s.token = p_token and s.revoked_at is null and s.expires_at > now()
  ) then
    raise exception 'Sesión de administrador inválida o vencida' using errcode = '28000';
  end if;
  return query select * from public.barber_services order by display_order, name;
end;
$$;

create or replace function public.barber_service_admin_save(
  p_token uuid, p_id integer, p_name text, p_description text,
  p_duration_minutes integer, p_price numeric, p_is_active boolean, p_display_order integer
)
returns public.barber_services
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_row public.barber_services;
begin
  if not exists (
    select 1 from public.barber_admin_sessions s
    where s.token = p_token and s.revoked_at is null and s.expires_at > now()
  ) then
    raise exception 'Sesión de administrador inválida o vencida' using errcode = '28000';
  end if;
  if nullif(trim(p_name), '') is null or p_duration_minutes not between 5 and 480 or p_price < 0 then
    raise exception 'Datos del servicio inválidos' using errcode = '22023';
  end if;
  if p_id is null then
    insert into public.barber_services(name, description, duration_minutes, price, is_active, display_order)
    values (trim(p_name), coalesce(p_description,''), p_duration_minutes, p_price, coalesce(p_is_active,true), coalesce(p_display_order,100))
    returning * into v_row;
  else
    update public.barber_services
      set name=trim(p_name), description=coalesce(p_description,''), duration_minutes=p_duration_minutes,
          price=p_price, is_active=coalesce(p_is_active,true), display_order=coalesce(p_display_order,100),
          updated_at=now()
      where id=p_id returning * into v_row;
    if not found then raise exception 'Servicio no encontrado' using errcode = 'P0002'; end if;
  end if;
  return v_row;
end;
$$;

create or replace function public.barber_promotion_admin_review(p_token uuid, p_id uuid, p_decision text)
returns public.barber_promotions
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_row public.barber_promotions;
begin
  if not exists (
    select 1 from public.barber_admin_sessions s
    where s.token = p_token and s.revoked_at is null and s.expires_at > now()
  ) then
    raise exception 'Sesión de administrador inválida o vencida' using errcode = '28000';
  end if;
  if p_decision not in ('approved','rejected','paused','pending_review','draft') then
    raise exception 'Decisión no válida' using errcode = '22023';
  end if;
  update public.barber_promotions
    set status=p_decision,
        approved_at=case when p_decision='approved' then now() else null end,
        updated_at=now()
    where id=p_id returning * into v_row;
  if not found then raise exception 'Promoción no encontrada' using errcode = 'P0002'; end if;
  return v_row;
end;
$$;

